/* =========================================================
   CRIAÇÃO DAS PERGUNTAS NA PÁGINA
   ========================================================= */

let questionNumber = 1;

const root = document.querySelector('#qa');

groups.forEach(([title, items]) => {

    /* Cria o bloco de cada categoria */

    const section = document.createElement('section');

    section.className = 'group reveal';

    section.innerHTML = `
        <div class="group-title">
            ${title}
        </div>
    `;


    /* Cria cada pergunta e resposta */

    items.forEach(([question, answer]) => {

        const number = String(questionNumber++)
            .padStart(2, '0');

        section.innerHTML += `
            <article class="card">

                <div class="num">
                    ${number}
                </div>

                <div class="content">

                    <p class="q">
                        ${question}
                    </p>

                    <p class="a">
                        ${answer}
                    </p>

                </div>

            </article>
        `;

    });


    /* Adiciona a categoria na página */

    root.appendChild(section);

});


/* =========================================================
   ANIMAÇÃO AO ROLAR A PÁGINA
   ========================================================= */

const observer = new IntersectionObserver(

    (entries) => {

        entries.forEach((entry) => {

            if (entry.isIntersecting) {
                entry.target.classList.add('visible');
            }

        });

    },

    {
        threshold: 0.08
    }

);


/* Observa todos os elementos com animação */

document
    .querySelectorAll('.reveal')
    .forEach((element) => {

        observer.observe(element);

    });
